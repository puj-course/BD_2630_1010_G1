CREATE VIEW V_ISTA AS

SELECT A.NAME AS STUDENT_NAME, A.COURSE_ID, B.NAME AS INSTRUCTORE_NAME
FROM (SELECT S.NAME, T.COURSE_ID
FROM STUDENT S JOIN TAKES T
    ON S.ID = T.ID) A
JOIN     
(SELECT I.NAME, C.COURSE_ID
FROM TEACHES C LEFT JOIN INSTRUCTOR I
    ON C.ID = I.ID) B
    ON A.COURSE_ID = B.COURSE_ID
GROUP BY A.NAME, A.COURSE_ID, B.NAME; 

GRANT SELECT ON V_ISTA TO IS101008;

