CREATE VIEW V_PREREQUISITO AS 
SELECT P.PREREQ_ID ID, C.TITLE NOMBRE
FROM COURSE C LEFT JOIN PREREQ P 
    ON C.COURSE_ID = P.COURSE_ID; 
    
